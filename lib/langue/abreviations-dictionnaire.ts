/**
 * DICTIONNAIRE DES ABRÉVIATIONS FR/EN (gen3 — périmètre « langue »).
 *
 * Objectif : permettre à gen3 de RECONNAÎTRE les abréviations réellement
 * utilisées par les utilisateurs (texto FR, tech, business FR, international,
 * médical, unités, messagerie EN, code) et de savoir QUAND un mot a été abrégé.
 *
 * Format d'entrée (clé = abréviation en minuscules) :
 *   - `expansion`  : forme développée (lecture naturelle, utilisée quand
 *     l'entrée n'est PAS ambiguë) ;
 *   - `registre`   : "texto" | "professionnel" | "technique" | "medical" |
 *     "international" | "unite" | "code" ;
 *   - `ambigu`     : true si l'abréviation a plusieurs lectures plausibles.
 *     Une entrée ambiguë n'est JAMAIS développée hors contexte : il faut que
 *     l'un des `senses[*].contexteMotsCles` corresponde aux mots voisins
 *     (fenêtre ±8 mots côté moteur, voir abreviations.ts) ;
 *   - `senses`     : lectures alternatives `{ expansion, contexteMotsCles }`.
 *     Le champ `expansion` principal reflète la lecture la plus fréquente
 *     (senses[0] pour les entrées ambiguës).
 *
 * Choix délibérés :
 *   - "etc." n'est PAS dans le dictionnaire (faux positif demandé par le
 *     propriétaire : « etc. » reste tel quel) ;
 *   - les vrais mots français courts ("de", "le", "si", "va", "un"…) ne sont
 *     jamais des clés, sauf s'ils sont protégés par `ambigu` ("sa", "si") ;
 *   - les unités ("km", "mg"…) ne sont JAMAIS développées collées à un
 *     chiffre (« 5 km », « 500 mg » restent intacts).
 */

